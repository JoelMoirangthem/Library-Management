import type { District, State } from '@/domain/types'

/** An official town from the LGD list. A town can lie in more than one district. */
export type Town = { id: string; stateId: string; name: string; districtIds: string[] }

export type PlaceData = {
  states: State[]
  districts: District[]
  towns: Town[]
  stateById: Map<string, State>
  districtById: Map<string, District>
  townById: Map<string, Town>
}

let data: PlaceData | null = null
let pending: Promise<PlaceData> | null = null

/**
 * Dummy mode only. Loads the same state, district and town lists the real database has (generated by
 * scripts/places/build.mjs). A separate file, downloaded on first use, so the live site never carries it.
 */
export function loadPlaces(): Promise<PlaceData> {
  if (data) return Promise.resolve(data)
  pending ??= import('./places.generated.json').then(({ default: raw }) => {
    const states = raw.states.map(([id, name, ut]) => ({ id, name, isUnionTerritory: ut === 1 }))
    const districts = raw.districts.map(([id, stateId, name]) => ({ id, stateId, name }))
    const towns = raw.towns.map(([id, stateId, name, districtIds]) => ({ id, stateId, name, districtIds }))
    data = {
      states,
      districts,
      towns,
      stateById: new Map(states.map((s) => [s.id, s])),
      districtById: new Map(districts.map((d) => [d.id, d])),
      townById: new Map(towns.map((t) => [t.id, t])),
    }
    return data
  })
  return pending
}

/** The loaded lists. Every mock repository call loads them first (see run() in db.ts). */
export function placeData(): PlaceData {
  if (!data) throw new Error('Place lists are not loaded yet: call loadPlaces() first.')
  return data
}
